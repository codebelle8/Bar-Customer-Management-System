export type TermsLine = { text: string; level: 0 | 1 | 2; bullet: boolean } | { blank: true }

export function parseTerms(src: string): TermsLine[] {
  return src.split('\n').map((raw) => {
    if (!raw.trim()) return { blank: true }
    const level = raw.startsWith('!!') ? 2 : raw.startsWith('!') ? 1 : 0
    const text = raw.slice(level)
    return { text, level: level as 0 | 1 | 2, bullet: text.startsWith('・') }
  })
}

